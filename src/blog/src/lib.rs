//! The `blog` template and its renderer: a consumer repository (`.pigeon/site.toml`,
//! `content/posts`, `content/pages`, `static/`) in, a static site out. See `docs/plans/blog.md`.
//!
//! Its own crate (`pigeon-blog`), owned by the `pigeon-sites` Worker's lane
//! (docs/plans/workers-split.md); it uses only `serde`, `serde_json`, `toml`, `sha2` and
//! `pulldown-cmark`, and builds natively for the smoke suite.
//!
//! Pure: no I/O, no clock, no environment. The same [`Input`] always renders the same bytes. The
//! renderer never sees a static file's bytes, only its path: the deploy copies `static/x` to `/x`.
//!
//! `blog@1` is noisypigeon's Zola theme `site-template-blog` at 1.0.5 (see `v1/UPSTREAM.md`),
//! with its templates written as Rust functions ([`pages`], [`feeds`]) and its Markdown rendered
//! as Zola 0.23.6 renders it ([`markdown`]). Its URLs are Zola's, so links to a site built by the
//! theme keep working.

pub mod content;
pub mod feeds;
pub mod markdown;
pub mod pages;
pub mod repo;
pub mod site;

use std::collections::{BTreeMap, BTreeSet};

use sha2::{Digest, Sha256};

/// The template a consumer names in `site.toml`.
pub const TEMPLATE: &str = "blog@1";

/// The exact version of `blog@1` this build carries. A deploy records it.
pub const VERSION: &str = "1.0.0";

/// The template's stylesheets, byte copies of upstream 1.0.5's, served at `/assets/css/`.
pub const CSS: [(&str, &str); 3] = [
    ("main.css", include_str!("v1/main.css")),
    ("tokens.css", include_str!("v1/tokens.css")),
    ("pigeon.css", include_str!("v1/pigeon.css")),
];

/// What a deploy hands the renderer.
#[derive(Clone, Debug, Default)]
pub struct Input {
    /// `.pigeon/site.toml`.
    pub site_toml: String,
    /// `content/posts/*.md`: file name and text.
    pub posts: Vec<(String, String)>,
    /// `content/pages/*.md`: file name and text.
    pub pages: Vec<(String, String)>,
    /// Every path under `static/`, relative to it, such as `assets/images/site/avatar.png`.
    pub statics: BTreeSet<String>,
    /// Where the site is canonically served, without a trailing slash, such as
    /// `https://example.com`. Used only where an absolute URL is required.
    pub base_url: String,
    /// The deployed commit, short, for the footer.
    pub commit: String,
    /// The commit's year, for the footer.
    pub commit_year: u16,
}

/// A rendered site.
#[derive(Clone, Debug, PartialEq)]
pub struct Output {
    /// Generated files by site path without a leading slash (`index.html`,
    /// `posts/x/index.html`, `assets/css/main.css`): bytes and content type.
    pub files: BTreeMap<String, (Vec<u8>, &'static str)>,
    /// Paths under `static/` to serve as they are, at the same path.
    pub statics: Vec<String>,
    /// [`TEMPLATE`].
    pub template: &'static str,
    /// [`VERSION`].
    pub version: &'static str,
    /// The template's digest: sha256 over its version and embedded files.
    pub digest: String,
}

/// Something wrong with the consumer's repository, and where.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Problem {
    /// The repository path, such as `content/posts/2025-01-02-x.md`.
    pub file: String,
    /// What is wrong and how to fix it.
    pub message: String,
}

impl std::fmt::Display for Problem {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: {}", self.file, self.message)
    }
}

/// Renders the consumer's repository, or lists everything wrong with it.
pub fn render(input: &Input) -> Result<Output, Vec<Problem>> {
    let mut problems = Vec::new();
    let settings = site::parse(&input.site_toml, &mut problems);
    let posts = content::parse_all(content::Kind::Post, &input.posts, &mut problems);
    let pages = content::parse_all(content::Kind::Page, &input.pages, &mut problems);
    let Some((settings, features)) = settings else {
        problems.sort();
        return Err(problems);
    };
    let site = Site::new(settings, features, posts, pages, input);
    site.check(&input.statics, &mut problems);
    let files = site.files();
    for path in files.keys() {
        if input.statics.contains(path) {
            problems.push(Problem {
                file: format!("static/{path}"),
                message: format!("/{path} is generated by {TEMPLATE}; remove this file"),
            });
        }
    }
    if !problems.is_empty() {
        problems.sort();
        problems.dedup();
        return Err(problems);
    }
    let files = files
        .into_iter()
        .map(|(path, (body, kind))| (path, (body.into_bytes(), kind)))
        .collect();
    Ok(Output {
        files,
        statics: input.statics.iter().cloned().collect(),
        template: TEMPLATE,
        version: VERSION,
        digest: digest(),
    })
}

/// The template's digest: sha256 over its version and embedded files.
pub fn digest() -> String {
    let mut h = Sha256::new();
    h.update(TEMPLATE.as_bytes());
    h.update(VERSION.as_bytes());
    for (name, css) in CSS {
        h.update(name.as_bytes());
        h.update(css.as_bytes());
    }
    h.finalize().iter().map(|b| format!("{b:02x}")).collect()
}

/// Everything the templates read: the settings, the features and the content, resolved.
#[derive(Clone, Debug)]
pub struct Site {
    /// `[site]` from `site.toml`, with the template's defaults filled in.
    pub settings: site::Settings,
    /// The effective features.
    pub features: site::Features,
    /// Posts, newest first; ties by file name.
    pub posts: Vec<content::Entry>,
    /// Pages, by file name.
    pub pages: Vec<content::Entry>,
    /// The `tags` taxonomy, by slug.
    pub tags: Vec<Tag>,
    /// [`Input::base_url`], without a trailing slash.
    pub base_url: String,
    /// [`Input::commit`].
    pub commit: String,
    /// [`Input::commit_year`].
    pub commit_year: u16,
}

/// One tag and its posts.
#[derive(Clone, Debug)]
pub struct Tag {
    /// The tag as written.
    pub name: String,
    /// Its URL segment: `/tags/{slug}/`.
    pub slug: String,
    /// Indexes into [`Site::posts`], newest first.
    pub posts: Vec<usize>,
}

impl Site {
    fn new(
        settings: site::Settings,
        features: site::Features,
        mut posts: Vec<content::Entry>,
        mut pages: Vec<content::Entry>,
        input: &Input,
    ) -> Self {
        let instant = |e: &content::Entry| e.date.as_ref().map(Date::instant);
        posts.sort_by(|a, b| {
            instant(b)
                .cmp(&instant(a))
                .then_with(|| a.path.cmp(&b.path))
        });
        pages.sort_by(|a, b| a.file.cmp(&b.file));
        let mut by_slug: BTreeMap<String, Tag> = BTreeMap::new();
        for (i, post) in posts.iter().enumerate() {
            for name in &post.tags {
                let slug = markdown::slugify(name);
                by_slug
                    .entry(slug.clone())
                    .or_insert_with(|| Tag {
                        name: name.clone(),
                        slug,
                        posts: Vec::new(),
                    })
                    .posts
                    .push(i);
            }
        }
        Site {
            settings,
            features,
            posts,
            pages,
            tags: by_slug.into_values().collect(),
            base_url: input.base_url.trim_end_matches('/').to_string(),
            commit: input.commit.clone(),
            commit_year: input.commit_year,
        }
    }

    /// The site's own paths: `/`, each entry, each alias, the tags. Site paths end in `/`.
    fn routes(&self) -> BTreeSet<String> {
        let mut out = BTreeSet::from(["/".to_string(), "/tags/".to_string()]);
        for e in self.posts.iter().chain(&self.pages) {
            out.insert(e.path.clone());
            for a in &e.aliases {
                out.insert(alias_path(a));
            }
        }
        for t in &self.tags {
            out.insert(format!("/tags/{}/", t.slug));
        }
        out
    }

    /// Checks what only the whole site can: missing static files, links to no page, and two
    /// things answering one URL.
    fn check(&self, statics: &BTreeSet<String>, problems: &mut Vec<Problem>) {
        let need = |file: &str, what: &str, path: &str, problems: &mut Vec<Problem>| {
            if !statics.contains(path.trim_start_matches('/')) {
                problems.push(Problem {
                    file: file.to_string(),
                    message: format!("{what} `{path}` is not under static/: add static{path}"),
                });
            }
        };
        let toml = ".pigeon/site.toml";
        let s = &self.settings;
        for (what, path) in [("avatar", &s.avatar), ("social_preview", &s.social_preview)] {
            if let Some(path) = path {
                need(toml, what, path, problems);
            }
        }
        for icon in &s.icons {
            need(toml, "icon", &icon.src, problems);
        }
        for f in [
            "/assets/images/site/favicon-32x32.png",
            "/assets/images/site/favicon-16x16.png",
            "/assets/images/site/apple-touch-icon.png",
        ] {
            need(toml, "the template's favicon", f, problems);
        }
        for e in self.posts.iter().chain(&self.pages) {
            if let Some(img) = &e.og_image {
                need(&e.file, "og_image", img, problems);
            }
        }
        let routes = self.routes();
        let names_a_page = |link: &str| {
            let path = link.split(['#', '?']).next().unwrap_or(link);
            let slash = if path.ends_with('/') {
                path.to_string()
            } else {
                format!("{path}/")
            };
            routes.contains(&slash) || statics.contains(path.trim_start_matches('/'))
        };
        if let Some(page) = &s.author_page
            && !names_a_page(page)
        {
            problems.push(Problem {
                file: toml.into(),
                message: format!("author_page `{page}` names no page or post"),
            });
        }
        for item in &s.nav {
            if item.link.starts_with('/') && !names_a_page(&item.link) {
                problems.push(Problem {
                    file: toml.into(),
                    message: format!(
                        "nav `{}` links to `{}`, which names no page or post",
                        item.title, item.link
                    ),
                });
            }
        }
        let mut owners: BTreeMap<String, &str> = BTreeMap::new();
        for e in self.posts.iter().chain(&self.pages) {
            for path in
                std::iter::once(e.path.clone()).chain(e.aliases.iter().map(|a| alias_path(a)))
            {
                if let Some(other) = owners.insert(path.clone(), &e.file) {
                    problems.push(Problem {
                        file: e.file.clone(),
                        message: format!("{path} is also {other}'s; give each URL one owner"),
                    });
                }
            }
        }
        for path in owners.keys() {
            if path == "/" || path.starts_with("/tags/") || path == "/assets/" {
                problems.push(Problem {
                    file: owners[path].to_string(),
                    message: format!("{path} belongs to the template; choose another"),
                });
            }
        }
    }

    /// Every generated file: site path (no leading slash) to body and content type.
    pub fn files(&self) -> BTreeMap<String, (String, &'static str)> {
        let html = "text/html; charset=utf-8";
        let mut out = BTreeMap::new();
        out.insert("index.html".to_string(), (pages::index(self), html));
        for e in &self.posts {
            out.insert(file_of(&e.path), (pages::post(self, e), html));
        }
        for e in &self.pages {
            out.insert(file_of(&e.path), (pages::page(self, e), html));
        }
        for e in self.posts.iter().chain(&self.pages) {
            for a in &e.aliases {
                out.insert(file_of(&alias_path(a)), (pages::alias(&e.path), html));
            }
        }
        out.insert("tags/index.html".into(), (pages::tags(self), html));
        for t in &self.tags {
            out.insert(
                format!("tags/{}/index.html", t.slug),
                (pages::tag(self, t), html),
            );
        }
        out.insert("404.html".into(), (pages::not_found(), html));
        out.insert(
            "posts/posts_feed.xml".into(),
            (feeds::atom(self), "application/atom+xml; charset=utf-8"),
        );
        out.insert(
            "sitemap.xml".into(),
            (feeds::sitemap(self), "application/xml; charset=utf-8"),
        );
        out.insert(
            "robots.txt".into(),
            (feeds::robots(self), "text/plain; charset=utf-8"),
        );
        out.insert(
            "manifest.json".into(),
            (feeds::manifest(self), "application/json"),
        );
        for (name, css) in CSS {
            out.insert(
                format!("assets/css/{name}"),
                (css.to_string(), "text/css; charset=utf-8"),
            );
        }
        out
    }
}

/// An alias as Zola writes it (`pages/names`, `/changelog/x/`) as a site path: `/pages/names/`.
pub fn alias_path(alias: &str) -> String {
    let a = alias.trim_matches('/');
    format!("/{a}/")
}

/// The file that serves a site path: `/posts/x/` is `posts/x/index.html`.
fn file_of(path: &str) -> String {
    format!("{}index.html", path.trim_start_matches('/'))
}

/// Escapes text for HTML and XML as Tera does: `& < > " ' /`.
pub fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#x27;"),
            '/' => out.push_str("&#x2F;"),
            c => out.push(c),
        }
    }
    out
}

/// A JSON string for a `<script type="application/ld+json">`, with `<` as `<`.
pub fn json(s: &str) -> String {
    serde_json::Value::String(s.to_string())
        .to_string()
        .replace('<', "\\u003c")
}

/// A date from front matter.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Date {
    /// Year, month (1 to 12), day, hour, minute, second, as written.
    pub ymdhms: (u16, u8, u8, u8, u8, u8),
    /// The offset from UTC in minutes, 0 when none was written.
    pub offset_min: i16,
    /// Whether a time was written (`2025-01-02T03:04:05Z`) or only a date (`2025-01-02`).
    pub has_time: bool,
}

const MONTHS: [&str; 12] = [
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December",
];

impl Date {
    /// The year.
    pub fn year(&self) -> u16 {
        self.ymdhms.0
    }

    /// `%Y-%m-%d`.
    pub fn ymd(&self) -> String {
        let (y, m, d, ..) = self.ymdhms;
        format!("{y:04}-{m:02}-{d:02}")
    }

    /// `%Y-%m-%dT%H:%M:%S%:z`, as the templates print dates: `2025-01-02T03:04:05+00:00`.
    pub fn iso(&self) -> String {
        let (_, _, _, h, mi, s) = self.ymdhms;
        format!(
            "{}T{h:02}:{mi:02}:{s:02}{}",
            self.ymd(),
            self.offset(':', false)
        )
    }

    /// The sitemap's `lastmod`, as Zola writes it: RFC 3339 (`Z` for UTC) when a time was
    /// written, else the date alone.
    pub fn lastmod(&self) -> String {
        if !self.has_time {
            return self.ymd();
        }
        let (_, _, _, h, mi, s) = self.ymdhms;
        format!(
            "{}T{h:02}:{mi:02}:{s:02}{}",
            self.ymd(),
            self.offset(':', true)
        )
    }

    /// `%b %-d`: `Jan 2`.
    pub fn month_day(&self) -> String {
        let (_, m, d, ..) = self.ymdhms;
        format!("{} {d}", &MONTHS[usize::from(m) - 1][..3])
    }

    /// `%Y %B %-d`: `2025 January 2`.
    pub fn long(&self) -> String {
        let (y, m, d, ..) = self.ymdhms;
        format!("{y} {} {d}", MONTHS[usize::from(m) - 1])
    }

    fn offset(&self, sep: char, z: bool) -> String {
        if z && self.offset_min == 0 {
            return "Z".into();
        }
        let sign = if self.offset_min < 0 { '-' } else { '+' };
        let m = self.offset_min.unsigned_abs();
        format!("{sign}{:02}{sep}{:02}", m / 60, m % 60)
    }

    /// The instant, in seconds, for ordering dates with different offsets.
    pub fn instant(&self) -> i64 {
        let (y, m, d, h, mi, s) = self.ymdhms;
        let (y, m) = (i64::from(y), i64::from(m));
        let (y, m) = if m <= 2 { (y - 1, m + 9) } else { (y, m - 3) };
        let days = 365 * y + y / 4 - y / 100 + y / 400 + (153 * m + 2) / 5 + i64::from(d);
        days * 86_400 + i64::from(h) * 3600 + i64::from(mi) * 60 + i64::from(s)
            - i64::from(self.offset_min) * 60
    }
}
