#!/bin/sh
# Writes the repo map that every AI agent run reads in its cached prompt prefix.
# Usage: sh ci/repo-map.sh [output-path]   (default: src/ai-agents/repo-map.md)
# The output holds no counts, dates or hashes, so it changes only when the layout does.
# A smoke scenario runs this script and fails when the committed file differs.
set -eu
LC_ALL=C
export LC_ALL

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
out=${1:-src/ai-agents/repo-map.md}
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# The workspace members, in Cargo.toml order.
members() {
    sed -n '/^members *= *\[/,/^\]/p' Cargo.toml | grep -o '"[^"]*"' | tr -d '"'
}

# One line of purpose for the crate in directory $1: the first `//!` line, else the description.
purpose() {
    d=$1
    for f in "$d/src/lib.rs" "$d/src/main.rs"; do
        if [ -f "$f" ]; then
            l=$(grep -m1 '^//!' "$f" | sed 's|^//! *||') || l=
            if [ -n "$l" ]; then
                printf '%s\n' "$l"
                return
            fi
        fi
    done
    l=$(grep -m1 '^description *=' "$d/Cargo.toml" | sed 's/^[^"]*"//; s/"[^"]*$//') || l=
    if [ -n "$l" ]; then
        printf '%s\n' "$l"
    else
        printf '(no crate docs)\n'
    fi
}

# The workspace crates a directory links directly, as paths like src/core.
direct() {
    grep -o 'path *= *"\.\./[^"]*"' "$1/Cargo.toml" 2>/dev/null |
        sed 's|^[^"]*"\.\./||; s|"$||' | grep -v '\.\.' | sed 's|^|src/|'
}

# Every workspace crate a directory links, directly or not, sorted.
linked() {
    seen=
    todo=$(direct "$1")
    while [ -n "$todo" ]; do
        next=
        for c in $todo; do
            case " $seen " in
            *" $c "*) ;;
            *)
                seen="$seen $c"
                next="$next $(direct "$c")"
                ;;
            esac
        done
        todo=$next
    done
    for c in $seen; do printf '%s\n' "$c"; done | sort
}

# The value of a key in one [[worker]] block of ci/workers.toml: block name $1, key $2.
wkey() {
    awk -v n="$1" -v k="$2" '
        /^\[\[worker\]\]/ { inb = 1; hit = 0; next }
        /^\[/ { inb = 0 }
        inb && $1 == "name" { gsub(/"/, "", $3); hit = ($3 == n) }
        inb && hit && $1 == k { gsub(/"/, "", $3); print $3; exit }
    ' ci/workers.toml
}

{
    echo '# Repo map'
    echo
    echo 'Generated by `ci/repo-map.sh`. Do not edit by hand. It lists the layout, not the code.'
    echo
    echo '## Workspace crates'
    echo
    echo 'Each crate lives in `src/<name>` (see `members` in `Cargo.toml`).'
    echo
    for m in $(members); do
        printf -- '- `%s`: %s\n' "$m" "$(purpose "$m")"
    done
    echo
    echo '## Workers'
    echo
    echo 'From `ci/workers.toml` and each Worker'"'"'s `wrangler.toml`. "Links" lists every'
    echo 'workspace crate the Worker crate pulls in, directly or not.'
    echo
    names=$(awk '/^\[\[worker\]\]/ { inb = 1; next } /^\[/ { inb = 0 } inb && $1 == "name" { gsub(/"/, "", $3); print $3 }' ci/workers.toml)
    for n in $names; do
        dir=$(wkey "$n" dir)
        script=$(wkey "$n" script)
        wr=
        if [ -f "$dir/wrangler.toml" ]; then wr=", config \`$dir/wrangler.toml\`"; fi
        printf -- '- `%s`: script `%s`, crate `%s`%s\n' "$n" "$script" "$dir" "$wr"
        printf '  - links: %s\n' "$(linked "$dir" | sed 's|^|`|; s|$|`|' | tr '\n' ' ' | sed 's/ $//; s/ /, /g')"
    done
    echo
    echo '## Where things live'
    echo
    echo '- Tools: the MCP tools are served from `src/capabilities/src` (`dispatch.rs` routes them,'
    echo '  one file per area). The AI agents tools are in `src/ai-agents/src/tools.rs` and'
    echo '  `src/ai-agents/src/prompts.rs`.'
    echo '- Policy and gate: `.pigeon/policy.toml` (the person changes it), `.claude/settings.json`.'
    echo '- Plans: `docs/plans/*.md`, one file per area, each ends with a Log. Start with'
    echo '  `docs/plans/README.md`.'
    echo '- Tests: only `tests/smoke.rs` and its area modules in `tests/smoke/`. A test name starts'
    echo '  with its Worker'"'"'s name. Never add a test elsewhere.'
    echo '  Modules:'
    for f in tests/smoke/*.rs; do
        b=${f##*/}
        printf '  `%s`' "${b%.rs}"
    done | sed 's/`  `/`, `/g'
    echo
    echo '- CI: `.pigeon/ci.toml` defines the jobs, `ci/runner` holds their scripts. Jobs:'
    grep -o '^\[jobs\.[^].]*\]' .pigeon/ci.toml | sed 's/^\[jobs\.//; s/\]$//' |
        tr '\n' ' ' | sed 's/ $//; s/ /`, `/g; s/^/  `/; s/$/`/'
    echo
    echo '  Run the gate with `sh ci/runner/test.sh`.'
    echo '- Deploy: `ci/deploy/deploy.sh` and one `ci/deploy/deploy-<worker>.sh` per capability'
    echo '  Worker. Scripts in `ci/deploy`:'
    for f in ci/deploy/*; do
        printf '  `%s`' "${f##*/}"
    done | sed 's/`  `/`, `/g'
    echo
    echo '- Worker ownership of paths (lanes): `ci/workers.toml`.'
    echo '- This map: `ci/repo-map.sh` writes `src/ai-agents/repo-map.md`.'
} >"$tmp"

mkdir -p "$(dirname "$out")"
cat "$tmp" >"$out"
